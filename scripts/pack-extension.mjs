#!/usr/bin/env node
/**
 * Package the browser extension for the Chrome Web Store / Edge Add-ons (or to share as a zip).
 *
 *   npm run ext:pack -- --server https://thisbut.up.railway.app [--version 1.0.1]
 *
 * Writes dist/extension/ (load-unpacked ready) and dist/thisbut-extension-<version>.zip.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith("--") ? [...acc, [a.slice(2), all[i + 1]]] : acc), []),
);
const server = (args.server || process.env.THISBUT_SERVER_URL || "").replace(/\/+$/, "");
if (!/^https:\/\//.test(server) && !/^http:\/\/localhost/.test(server)) {
  console.error("Usage: npm run ext:pack -- --server https://your-thisbut-server [--version x.y.z]");
  console.error("(Published extensions need an https server URL.)");
  process.exit(1);
}

const root = process.cwd();
const src = path.join(root, "extension");
const out = path.join(root, "dist", "extension");
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(src, { recursive: true })) {
  const from = path.join(src, f);
  if (fs.statSync(from).isDirectory() || f === "README.md") continue;
  fs.mkdirSync(path.dirname(path.join(out, f)), { recursive: true });
  fs.copyFileSync(from, path.join(out, f));
}
fs.writeFileSync(
  path.join(out, "config.js"),
  `// Generated by scripts/pack-extension.mjs\nself.THISBUT_CONFIG = { serverUrl: ${JSON.stringify(server)} };\n`,
);
const manifest = JSON.parse(fs.readFileSync(path.join(out, "manifest.json"), "utf8"));
if (args.version) manifest.version = args.version;
manifest.homepage_url = server;
fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

if (manifest.description.length > 132) throw new Error(`manifest description is ${manifest.description.length} chars (max 132)`);
const zip = path.join(root, "dist", `thisbut-extension-${manifest.version}.zip`);
fs.rmSync(zip, { force: true });
try {
  execFileSync("zip", ["-r", "-q", "-X", zip, "."], { cwd: out });
} catch {
  // no `zip` binary (e.g. Windows): fall back to Python's zipfile
  execFileSync("python3", ["-c", `import shutil,sys; shutil.make_archive(sys.argv[1][:-4], 'zip', sys.argv[2])`, zip, out]);
}
console.log(`Server:   ${server}`);
console.log(`Unpacked: ${path.relative(root, out)}/  (chrome://extensions → Load unpacked)`);
console.log(`Zip:      ${path.relative(root, zip)}  (upload to the Chrome Web Store / Edge Add-ons)`);
